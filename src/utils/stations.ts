// Dictionary lookup O(1) berdasarkan kode ICAO (uppercase)
const STATION_MAP: Record<string, StametBandara> = DAFTAR_STAMET_BANDARA.reduce(
  (acc, item) => {
    acc[item.icao.toUpperCase()] = item;
    return acc;
  },
  {} as Record<string, StametBandara>,
);

/**
 * Mengambil detail Stasiun Meteorologi & Bandar Udara berdasarkan kode ICAO.
 */
export function getStationByIcao(icao?: string | null): StametBandara | null {
  if (!icao) return null;
  return STATION_MAP[icao.trim().toUpperCase()] || null;
}
